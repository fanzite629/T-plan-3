'use strict';
const assert=require('node:assert/strict'),T=require('../task-timer'),G=require('../core');
const now=Date.parse('2026-10-22T12:00:00+08:00');
const input={title:'子网练习',minutes:45,cutoffMode:'budget',energy:'medium',completionCriterion:'独立完成两道子网题并解释错因'};
let b=T.start(T.empty(),input,now,'learning-test');
assert.equal(b.active.completionCriterion,input.completionCriterion);
assert.equal(b.active.cutoff,now+45*60000);
b=T.control(b,'pause',now+60000);b=T.control(b,'resume',now+120000);
assert.equal(b.active.cutoff,now+45*60000);
b=T.control(b,'finish',now+180000);
const saved=T.decide(b,{decision:'done',blocker:'独立完成两题',next:'明天回测'},now+180000);
assert.equal(saved.records[0].completionCriterion,input.completionCriterion);
assert.equal(saved.records[0].elapsedMs,120000);
assert.equal(saved.draft.completionCriterion,undefined);
const s={...G.newState(),timerBoard:saved};
assert.deepEqual(G.parseImport(G.exportData(s)).state,s);
assert.equal(s.logs.length,0);
console.log('PASS criterion persists through timing and review/export/import; new task clears; no implicit effort');
const legacy=structuredClone(s);delete legacy.timerBoard.records[0].completionCriterion;
assert.deepEqual(G.parseImport(G.exportData(legacy)).state,legacy);
assert.throws(()=>T.start(T.empty(),{...input,completionCriterion:'a'.repeat(501)},now));
const bad=structuredClone(s);bad.timerBoard.records[0].completionCriterion={text:'bad'};
assert.throws(()=>G.validateState(bad));
const extended=T.decide(b,{decision:'extend',blocker:'条件混淆',next:'核对适用条件',minutes:5},now+180000);
assert.equal(extended.active.cutoff,b.active.cutoff);
assert.equal(extended.active.completionCriterion,input.completionCriterion);
console.log('PASS old JSON exact roundtrip, invalid new fields rejected, extension retains fixed deadline and criterion');
